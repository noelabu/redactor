import AppKit
import Foundation
import Observation
import RedactorCore

/// Watches the clipboard and redacts copied text: the rules' version goes on the clipboard right
/// away, the AI-checked version replaces it if nothing new was copied meanwhile. The original is
/// kept in memory only, for "Restore original", until the next copy.
@MainActor
@Observable
final class ClipboardGuard {
    nonisolated static let category = "clipboard-redacted"
    nonisolated static let restoreAction = "restore-original"
    private static let notificationID = "clipboard-redacted"
    private static let enabledKey = "autoRedactClipboard"
    private static let excludedKey = "clipboardExcludedBundleIDs"
    /// Copies this large are left alone; the rules would stall the Mac.
    private static let maxCharacters = 1_000_000
    /// Password managers and other apps mark copies Redactor must not touch (nspasteboard.org).
    private static let skippedTypes: Set<NSPasteboard.PasteboardType> = [
        .init("org.nspasteboard.ConcealedType"), .init("org.nspasteboard.TransientType"), .init("org.nspasteboard.AutoGeneratedType"),
    ]

    var isEnabled: Bool {
        didSet {
            UserDefaults.standard.set(isEnabled, forKey: Self.enabledKey)
            // Whatever was copied while paused stays as it is.
            if isEnabled { lastSeen = pasteboard.changeCount }
        }
    }
    private(set) var excludedBundleIDs: [String] {
        didSet { UserDefaults.standard.set(excludedBundleIDs, forKey: Self.excludedKey) }
    }
    /// Overlapping jobs (a new copy while the AI checks the last one) each count until they finish.
    private var activeJobs = 0
    var isWorking: Bool { activeJobs > 0 }
    private(set) var hasRestorable = false
    /// The last app other than Redactor to be frontmost, for "Exclude <app>" (the menu makes Redactor frontmost).
    private(set) var lastExternalApp: (bundleID: String, name: String)?

    @ObservationIgnored private let notifier: Notifier
    @ObservationIgnored private let pasteboard = NSPasteboard.general
    @ObservationIgnored private var lastSeen = 0
    /// The changeCount of Redactor's own last write, so it is never treated as a new copy.
    @ObservationIgnored private var lastOwnWrite: Int?
    @ObservationIgnored private var job: Task<Void, Never>?
    @ObservationIgnored private var poller: Task<Void, Never>?
    @ObservationIgnored private var original: (text: String, token: Int)?

    init(notifier: Notifier) {
        self.notifier = notifier
        UserDefaults.standard.register(defaults: [Self.enabledKey: true])
        isEnabled = UserDefaults.standard.bool(forKey: Self.enabledKey)
        excludedBundleIDs = UserDefaults.standard.stringArray(forKey: Self.excludedKey) ?? []
    }

    func start() {
        // Whatever is on the clipboard at launch is left alone.
        lastSeen = pasteboard.changeCount
        // Loads the AI model now, so the first copy isn't checked while it is still loading.
        Task.detached(priority: .utility) { FoundationModelsDetector.prewarm() }
        NSWorkspace.shared.notificationCenter.addObserver(
            forName: NSWorkspace.didActivateApplicationNotification, object: nil, queue: .main
        ) { [weak self] note in
            guard let app = note.userInfo?[NSWorkspace.applicationUserInfoKey] as? NSRunningApplication,
                  let id = app.bundleIdentifier, id != Bundle.main.bundleIdentifier else { return }
            let name = app.localizedName ?? id
            MainActor.assumeIsolated { self?.lastExternalApp = (id, name) }
        }
        poller = Task { [weak self] in
            while !Task.isCancelled {
                self?.poll()
                try? await Task.sleep(for: .milliseconds(250), tolerance: .milliseconds(50))
            }
        }
    }

    func exclude(_ bundleID: String) {
        guard !excludedBundleIDs.contains(bundleID) else { return }
        excludedBundleIDs.append(bundleID)
    }

    func include(_ bundleID: String) {
        excludedBundleIDs.removeAll { $0 == bundleID }
    }

    static func appName(for bundleID: String) -> String {
        NSWorkspace.shared.urlForApplication(withBundleIdentifier: bundleID)
            .map { FileManager.default.displayName(atPath: $0.path).replacingOccurrences(of: ".app", with: "") } ?? bundleID
    }

    /// Writes the original back. `token` is the copy a banner was about; a stale one does nothing.
    func restore(token: Int? = nil) {
        guard let original, token == nil || token == original.token else {
            notifier.post("Original no longer available")
            return
        }
        job?.cancel()
        write(original.text)
        self.original = nil
        hasRestorable = false
        notifier.remove(identifier: Self.notificationID)
    }

    private func poll() {
        let count = pasteboard.changeCount
        guard count != lastSeen else { return }
        lastSeen = count
        guard count != lastOwnWrite else { return }

        // A new copy: the previous original is no longer restorable.
        original = nil
        hasRestorable = false
        job?.cancel()

        guard isEnabled else { return }
        let types = Set(pasteboard.types ?? [])
        guard types.isDisjoint(with: Self.skippedTypes), !types.contains(.fileURL) else { return }
        if let front = NSWorkspace.shared.frontmostApplication?.bundleIdentifier, excludedBundleIDs.contains(front) { return }
        guard let text = pasteboard.string(forType: .string), !text.isEmpty else { return }
        guard (text as NSString).length <= Self.maxCharacters else {
            notifier.post("Copied text is too large to check. It was left as is.")
            return
        }
        job = Task { await process(text, copy: count) }
    }

    private func process(_ text: String, copy: Int) async {
        activeJobs += 1
        defer { activeJobs -= 1 }
        var expected = copy
        do {
            let rules = try await Task.detached(priority: .userInitiated) { try await TextRedactionEngine.run(text) }.value
            guard !Task.isCancelled, pasteboard.changeCount == expected else { return }
            if rules.changed {
                expected = write(rules.text)
                keepOriginal(text, copy: copy)
            }

            guard Self.aiEligible(text) else {
                notifyIfRedacted(rules, copy: copy)
                return
            }
            let checked = try await Task.detached(priority: .utility) {
                try await TextRedactionEngine.run(text, ai: FoundationModelsDetector())
            }.value
            // Only if the clipboard still holds what Redactor left there.
            guard !Task.isCancelled, pasteboard.changeCount == expected else { return }
            if checked.changed, checked.text != rules.text {
                write(checked.text)
                keepOriginal(text, copy: copy)
            }
            notifyIfRedacted(checked, copy: copy)
        } catch {
            // The original is still on the clipboard: clear it. A rules version already written
            // passed its own double-check, so it stays.
            if pasteboard.changeCount == copy { failClosed() }
        }
    }

    private static func aiEligible(_ text: String) -> Bool {
        (text as NSString).length <= TextRedactionEngine.aiCharacterLimit
            && text.contains(where: \.isLetter)
            && FoundationModelsDetector.unavailableReason == nil
    }

    private func keepOriginal(_ text: String, copy: Int) {
        original = (text, copy)
        hasRestorable = true
    }

    private func notifyIfRedacted(_ result: TextRedactionResult, copy: Int) {
        guard result.changed else { return }
        let n = result.replacements
        notifier.post(
            "Redacted \(n) item\(n == 1 ? "" : "s") in copied text",
            identifier: Self.notificationID, category: Self.category, userInfo: ["token": copy]
        )
    }

    /// Plain text only: clearing drops the RTF and HTML copies of the original.
    @discardableResult
    private func write(_ text: String) -> Int {
        pasteboard.clearContents()
        guard pasteboard.setString(text, forType: .string) else {
            failClosed()
            return pasteboard.changeCount
        }
        markOwnWrite()
        return pasteboard.changeCount
    }

    private func failClosed() {
        pasteboard.clearContents()
        markOwnWrite()
        original = nil
        hasRestorable = false
        notifier.post("Couldn't check copied text. The clipboard was cleared.")
    }

    private func markOwnWrite() {
        lastOwnWrite = pasteboard.changeCount
        lastSeen = pasteboard.changeCount
    }
}
